/* s mod l, for a 32-byte little-endian s in [0, 2^256): zero-extend to the
 * 64-byte input sc25519_reduce expects and reduce in a local buffer.  Every
 * scalar-multiplication entry point canonicalises through here, so the group
 * operation is a function of (s mod l) — which is what the public contract
 * promises ([s]P == [s mod l]P, and the linearity identity
 * point_from_scalar(a) + point_from_scalar(b) == point_from_scalar(a + b)
 * for every 32-byte input, reduced or not).  The scrub is INVARIANT-6; the
 * buffer holds the secret on the comb path. */
static void sc25519_reduce32(uint8_t out[32], const uint8_t s[32]) {
    uint8_t wide[64];
    memcpy(wide, s, 32);
    ama_secure_memzero(wide + 32, 32);
    sc25519_reduce(wide);
    memcpy(out, wide, 32);
    ama_secure_memzero(wide, sizeof wide);
}

/* Signed W-bit comb digits of a reduced scalar (s < l < 2^253).
 *
 * Unsigned W-bit digits are extracted first — digit i is bits [Wi, Wi+W) —
 * then rebalanced by carry so every digit lies in [-2^(W-1), 2^(W-1) - 1],
 * which lets the comb table hold only the positive multiples 1..2^(W-1) and
 * apply the sign by negation.  The carry out of the last rebalanced digit is
 * added to the top digit, which can therefore reach 2^(W-1) exactly; the
 * selection routine accepts that magnitude.  Because s < 2^253 the top
 * digit's own bits are already small, so no carry escapes the digit count.
 *
 * CONSTANT TIME: byte indices and shifts depend on i only; the carry is
 * computed arithmetically.  The digit array is the secret's expansion and is
 * scrubbed by the caller (INVARIANT-6). */
static void ed25519_comb_digits(int8_t e[AMA_ED25519_COMB_DIGITS], const uint8_t s[32]) {
    const uint32_t mask = (1u << AMA_ED25519_COMB_WINDOW) - 1u;
    const int32_t half = (int32_t)1 << (AMA_ED25519_COMB_WINDOW - 1);
    int32_t carry = 0;
    int i;

    for (i = 0; i < AMA_ED25519_COMB_DIGITS; i++) {
        const int bit = i * AMA_ED25519_COMB_WINDOW;
        const int byte = bit >> 3;
        const int shift = bit & 7;
        uint32_t v = (uint32_t)s[byte];
        if (byte + 1 < 32) {
            v |= (uint32_t)s[byte + 1] << 8;
        }
        e[i] = (int8_t)((v >> shift) & mask);
    }
    for (i = 0; i < AMA_ED25519_COMB_DIGITS - 1; i++) {
        int32_t v = (int32_t)e[i] + carry;
        carry = (v + half) >> AMA_ED25519_COMB_WINDOW;   /* 0 or 1 */
        e[i] = (int8_t)(v - (carry << AMA_ED25519_COMB_WINDOW));
    }
    e[AMA_ED25519_COMB_DIGITS - 1] = (int8_t)((int32_t)e[AMA_ED25519_COMB_DIGITS - 1] + carry);
}

/* Width-w wNAF expansion of a 32-byte scalar: 256 signed digits, each odd in
 * [-(2^(w-1) - 1), 2^(w-1) - 1] or zero.  PUBLIC scalars only — the digit
 * extraction is variable-time by construction.
 *
 * The scalar is reduced mod l first, and the reduction is load-bearing, not
 * hygiene.  A width-w wNAF of a 256-bit integer needs up to 257 digits, and
 * the compensation step for a negative digit ADDS to the running value, so a
 * digit selected near the top of an unreduced scalar carries out of limb 7.
 * With 256 slots and eight 32-bit limbs that carry was discarded and the
 * 257th digit never emitted, so the recoding silently represented s - 2^256
 * for ~17% of uniform 32-byte scalars — ff..ff recoded as -1 and
 * ama_ed25519_scalarmult_public(out, ff..ff, B) returned -B with AMA_SUCCESS.
 * After reducing, s < l < 2^253: at most 254 digits, the running value stays
 * below 2^254, and neither the slot count nor the limb count can overflow. */
static void sc25519_to_wnaf(int8_t wnaf[256], const uint8_t scalar[32], int w) {
    uint32_t s[8];
    uint8_t reduced[32];
    int i, pos;
    const uint32_t mask = ((uint32_t)1 << w) - 1u;
    const int32_t half = (int32_t)1 << (w - 1);
    const int32_t full = (int32_t)1 << w;

    sc25519_reduce32(reduced, scalar);
    for (i = 0; i < 8; i++) {
        s[i] = (uint32_t)reduced[4 * i]
             | ((uint32_t)reduced[4 * i + 1] << 8)
             | ((uint32_t)reduced[4 * i + 2] << 16)
             | ((uint32_t)reduced[4 * i + 3] << 24);
    }
    for (pos = 0; pos < 256; pos++) {
        int32_t digit = 0;
        if (s[0] & 1u) {
            digit = (int32_t)(s[0] & mask);
            if (digit >= half) digit -= full;
            if (digit < 0) {
                uint64_t carry = (uint64_t)(uint32_t)(-digit);
                for (i = 0; i < 8; i++) {
                    carry += (uint64_t)s[i];
                    s[i] = (uint32_t)carry;
                    carry >>= 32;
                }
            } else {
                uint64_t borrow = 0;
                uint64_t sub = (uint64_t)(uint32_t)digit;
                for (i = 0; i < 8; i++) {
                    uint64_t val = (uint64_t)s[i] - sub - borrow;
                    s[i] = (uint32_t)val;
                    borrow = (val >> 63) & 1;
                    sub = 0;
                }
            }
        }
        wnaf[pos] = (int8_t)digit;
        for (i = 0; i < 7; i++) {
            s[i] = (s[i] >> 1) | (s[i + 1] << 31);
        }
        s[7] >>= 1;
    }
}

/* ============================================================================
 * GROUP-LEVEL HELPERS (radix-independent glue around the dispatch)
 * ============================================================================ */

/* out = [s]B in constant time, for any 32-byte s (reduced mod l here). */
static void ed25519_scalarmult_base(uint8_t out[32], const uint8_t s[32]) {
    uint8_t reduced[32];
    int8_t e[AMA_ED25519_COMB_DIGITS];
    sc25519_reduce32(reduced, s);
    ed25519_comb_digits(e, reduced);
    ED_DISPATCH(ama_ed25519_ge_scalarmult_base, out, e);
    ama_secure_memzero(reduced, sizeof reduced);
    ama_secure_memzero(e, sizeof e);
}

