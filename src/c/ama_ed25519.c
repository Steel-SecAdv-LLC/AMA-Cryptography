/**
 * @file ama_ed25519.c
 * @brief Ed25519 digital signatures (RFC 8032) — the in-house backend.
 * @author Andrew E. A., Steel Security Advisors LLC
 * @date 2026-04-06
 *
 * Twisted Edwards curve -x^2 + y^2 = 1 + d x^2 y^2 over GF(2^255 - 19),
 * d = -121665/121666, base point of order
 * l = 2^252 + 27742317777372353535851937790883648493.
 *
 * STRUCTURE
 *
 * This file owns everything that is independent of the field representation:
 * the RFC 8032 protocol (hashing, clamping, the canonical-encoding rules),
 * the scalar arithmetic mod l, the recoding of scalars into comb and wNAF
 * digits, and the public API.  The group arithmetic — point addition,
 * doubling, the constant-time fixed-base comb, the variable-time wNAF ladders,
 * compression and decompression — lives once in
 * src/c/internal/ama_ed25519_ge.h and is instantiated over two fields:
 *
 *   fe51       radix 2^51, five limbs (src/c/fe51.h).  Instantiated below,
 *              in this translation unit.  Every target compiles it; it is the
 *              only path on AArch64 and on MSVC.
 *   fe64-mulx  radix 2^64, four limbs, the MULX+ADX multiply and square
 *              kernel.  Instantiated in src/c/x86/ama_ed25519_fe64_mulx.c,
 *              compiled per-file with -mbmi2 -madx on x86-64 GCC/Clang, and
 *              selected here at run time when ama_cpuid_has_x25519_mulx()
 *              reports BMI2 and ADX — the same gate X25519 uses.
 *
 * Both instantiations read the same static base-point tables
 * (src/c/internal/ama_ed25519_tables.h, generated by
 * tools/gen_ed25519_tables.py in each radix) and produce byte-identical
 * results; tests/c/test_ed25519_fe51_mulx_equiv.c pins that on every x86-64
 * host that has both.  There is no lazy initialisation anywhere on this path:
 * the tables are `static const`, and no function in this file or in the
 * template writes file-scope state.
 *
 * SECURITY PROPERTIES
 * - Constant-time field arithmetic on every secret-scalar path.
 * - Constant-time fixed-base scalar multiplication: fixed digit count, a
 *   table selection that reads every entry of its row and combines with
 *   masks, sign applied by masked swap and masked negate.  INVARIANT-12.
 * - Secret-derived stack state is scrubbed on every exit (INVARIANT-6).
 * - Scalar clamping and the RFC 8032 canonical-encoding rules for S, R, the
 *   public key's y and the x = 0 sign bit (INVARIANT-26, INVARIANT-38).
 *
 * The variable-time routines (verify, batch verify, the public scalar-mult
 * primitives FROST uses) take PUBLIC scalars only and say so at each site.
 */

