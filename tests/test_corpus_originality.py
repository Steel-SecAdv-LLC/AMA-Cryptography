def test_a_subprocess_invocation_of_openssl_is_caught(tool: ModuleType, tmp_path: Path) -> None:
    """The exact shape the removed generator used."""
    (tmp_path / "tools").mkdir()
    (tmp_path / "tools" / "gen.py").write_text(
        "import subprocess\n"
        'subprocess.run(["openssl", "genpkey", "-algorithm", "EC"], check=True)\n'
    )
    problems = tool.scan_for_binary_invocations(tmp_path)
    assert any("openssl" in p and "gen.py" in p for p in problems), problems


@pytest.mark.parametrize("binary", ["gpg", "certtool", "keytool", "certutil"])
def test_other_cryptographic_binaries_are_caught(
    tool: ModuleType, tmp_path: Path, binary: str
) -> None:
    """Not an OpenSSL-shaped rule: any other implementation counts."""
    (tmp_path / "tests").mkdir()
    (tmp_path / "tests" / "t.py").write_text(
        f'import subprocess\nsubprocess.check_output("{binary} --version", shell=True)\n'
    )
    problems = tool.scan_for_binary_invocations(tmp_path)
    assert any(binary in p for p in problems), problems


def test_the_shipped_package_is_in_scope(tool: ModuleType, tmp_path: Path) -> None:
    """INVARIANT-1's strongest clause is about the shipped package, not the tests.

    ``legacy_compat.py`` shelled out to ``openssl ts`` to build and verify
    RFC 3161 timestamps — a competing implementation performing a cryptographic
    operation inside AMA at *runtime*, which is what INVARIANT-1 forbids in as
    many words. The scan originally covered ``tests/`` and ``tools/`` only and
    recorded that as an exception in its docstring. The exception is gone and
    so is the blind spot; this is what keeps it gone.
    """
    assert "ama_cryptography" in tool.SCAN_ROOTS, (
        "the shipped package must be scanned — it carries the strongest form of " "the rule"
    )
    (tmp_path / "ama_cryptography").mkdir()
    (tmp_path / "ama_cryptography" / "legacy_compat.py").write_text(
        "import subprocess\n"
        'subprocess.run(["openssl", "ts", "-query", "-data", "-"], capture_output=True)\n'
    )
    problems = tool.scan_for_binary_invocations(tmp_path)
    assert any("openssl" in p and "legacy_compat.py" in p for p in problems), problems


def test_the_real_package_invokes_no_cryptographic_binary(tool: ModuleType) -> None:
    """The live tree, not a fixture. This is the assertion that would have
    failed before the RFC 3161 work and must never fail again."""
    problems = [p for p in tool.scan_for_binary_invocations() if "ama_cryptography" in p]
    assert problems == [], problems


def test_a_mention_in_prose_is_not_a_finding(tool: ModuleType, tmp_path: Path) -> None:
    """This tree is full of "replaces OpenSSL X" comments — they are originality
    *claims*, and flagging them would make the gate un-satisfiable and push a
    maintainer to delete accurate documentation."""
    (tmp_path / "tools").mkdir()
    (tmp_path / "tools" / "note.py").write_text(
        '"""Replaces OpenSSL EVP_Digest; no openssl dependency."""\n'
        "# openssl is not used here\n"
        'OPENSSL_NOTE = "openssl"\n'
        "import subprocess\n"
        'subprocess.run(["python3", "-c", "pass"], check=True)\n'
    )
    assert tool.scan_for_binary_invocations(tmp_path) == []


def test_a_corpus_file_citing_a_non_standards_source_is_caught(
    tool: ModuleType, tmp_path: Path
) -> None:
    corpus = tmp_path / "keyformats"
    corpus.mkdir()
    (corpus / "vendor.json").write_text(
        json.dumps(
            {
                "source": {"url": "https://example.com/keys", "title": "t", "revision": "r"},
                "records": [],
            }
        )
    )
    problems = tool.scan_corpus_sources(corpus)
    assert any("not a standards-body archive" in p for p in problems), problems


def test_a_directory_of_key_files_in_the_corpus_is_caught(tool: ModuleType, tmp_path: Path) -> None:
    """How the third-party material was carried, so it is caught structurally
    and not only by the URL check."""
    corpus = tmp_path / "keyformats"
    (corpus / "somevendor").mkdir(parents=True)
    (corpus / "ok.json").write_text(
        json.dumps(
            {
                "source": {
                    "url": "https://www.rfc-editor.org/rfc/rfc9500.txt",
                    "title": "t",
                    "revision": "r",
                },
                "records": [],
            }
        )
    )
    # Deliberately *not* a literal PEM header: the check under test keys off
    # the directory, not the contents, and a real header here would be a finding
    # for tools/check_secrets.py (INVARIANT-23) in this very file.
    (corpus / "somevendor" / "P-256.key.pem").write_text("placeholder\n")
    problems = tool.scan_corpus_sources(corpus)
    assert any("unexpected directory" in p for p in problems), problems


def test_a_reference_encoder_that_imports_the_production_one_is_caught(
    tool: ModuleType, tmp_path: Path
) -> None:
    """The one-line change that would silently void every differential test."""
    path = tmp_path / "ref.py"
    path.write_text("from ama_cryptography._asn1 import der_sequence\n")
    problems = tool.check_reference_encoder(path)
    assert any("imports ama_cryptography" in p for p in problems), problems

    path.write_text("import ama_cryptography.key_formats as kf\n")
    assert tool.check_reference_encoder(path) != []


def test_a_missing_reference_encoder_is_a_failure(tool: ModuleType, tmp_path: Path) -> None:
    """Fail closed: the reference is what replaced the third-party corpus, so
    its absence must not read as everything being fine."""
    assert tool.check_reference_encoder(tmp_path / "gone.py") != []
