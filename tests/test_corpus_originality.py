"""INVARIANT-36 — no third-party cryptographic implementation in the validation path.

``tools/check_corpus_originality.py`` enforces that AMA's correctness is measured
against published specifications and against its own reference encoder, never
against another cryptographic product. These tests pin both directions: the
repository passes today, and each class of violation is reproduced and required
to be caught.

The invariant exists because the repository failed it once. The key-format
conformance corpus carried twelve PEM files generated by OpenSSL, vendored as
the answer key for EC PKCS#8 and SPKI because RFC 5915 and RFC 5480 publish no
worked examples. Nothing linked or invoked OpenSSL at build or run time — but a
competing implementation's output was the thing AMA's correctness was measured
against, inside AMA's own repository, in a project whose stated position is that
it depends on no other cryptographic implementation.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from types import ModuleType

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
TOOL_PATH = REPO_ROOT / "tools" / "check_corpus_originality.py"


def _load_tool() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_corpus_originality", TOOL_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def tool() -> ModuleType:
    return _load_tool()


# ---------------------------------------------------------------------------
# The anchor
# ---------------------------------------------------------------------------
def test_the_repository_holds_the_invariant(tool: ModuleType) -> None:
    assert tool.scan_for_binary_invocations() == []
    assert tool.scan_corpus_sources() == []
    assert tool.check_reference_encoder() == []


def test_the_cli_reports_success(tool: ModuleType) -> None:
    assert tool.main() == 0


def test_no_openssl_key_material_remains_anywhere_in_the_corpus() -> None:
    """The specific thing that was removed, asserted by name.

    Stated as its own test rather than folded into the generic scan, because
    this is the finding a reviewer will want to be able to point at.
    """
    corpus = REPO_ROOT / "tests" / "kat" / "keyformats"
    assert not (corpus / "openssl").exists(), (
        "the OpenSSL key corpus is back; RFC 9500 §2.3 publishes the EC keys it "
        "was standing in for"
    )
    for path in corpus.rglob("*"):
        assert path.suffix != ".pem", (
            f"{path} is a loose PEM file. Every vendored record lives in a JSON "
            "file that names the document it came from."
        )


def test_every_corpus_file_cites_an_rfc(tool: ModuleType) -> None:
    corpus = REPO_ROOT / "tests" / "kat" / "keyformats"
    seen = 0
    for path in sorted(corpus.glob("*.json")):
        source = json.loads(path.read_text())["source"]
        assert any(host in source["url"] for host in tool.STANDARDS_HOSTS), path.name
        assert source["title"] and source["revision"], path.name
        seen += 1
    assert seen >= 5, f"only {seen} corpus files found; the scan is not resolving"


