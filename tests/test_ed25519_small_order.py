#: The identity's canonical encoding, ``y = 1`` with the x-sign bit clear.
IDENTITY = SMALL_ORDER_ENCODINGS[2][1]


def verify_both(signature: bytes, message: bytes, public_key: bytes) -> bool:
    """Put one tuple to both entry points and require them to agree.

    Batch verification is a per-entry loop over ``ama_ed25519_verify``, so the
    two agreeing is a property of the code's shape rather than of a check
    duplicated in the batch path — which is exactly why it is asserted on
    every vector instead of argued once.
    """
    single = native_ed25519_verify(signature, message, public_key)
    batch = native_ed25519_batch_verify([(message, signature, public_key)])[0]
    assert single == batch, "batch verify disagreed with single verify on one 64-byte string"
    return single


class TestUniversalForgery:
    """``A = identity``: one signature, valid for every message.

    The audited finding. Each of these satisfies ``[S]B - R - [h]A = O`` for
    every message, so nothing but the small-order rule stands between them and
    acceptance.
    """

    @pytest.mark.parametrize("scalar,signature", UNIVERSAL_FORGERIES)
    @pytest.mark.parametrize("message", UNIVERSAL_MSGS)
    def test_forgery_is_rejected(self, scalar: int, signature: bytes, message: bytes) -> None:
        assert verify_both(signature, message, IDENTITY) is False

    @pytest.mark.parametrize("scalar,signature", UNIVERSAL_FORGERIES)
    def test_the_scalar_is_canonical(self, scalar: int, signature: bytes) -> None:
        """The rejection is not INVARIANT-26 doing the work by accident.

        ``S`` is 1, 5 or 12345 — far below ``L`` — so the canonical-``S``
        range check accepts every one of these signatures. If it did not, the
        test above would pass for the wrong reason.
        """
        L = 2**252 + 27742317777372353535851937790883648493
        s_half = int.from_bytes(signature[32:], "little")
        assert s_half == scalar
        assert s_half < L

    @pytest.mark.parametrize("scalar,signature", UNIVERSAL_FORGERIES)
    def test_the_r_half_is_not_itself_small_order(self, scalar: int, signature: bytes) -> None:
        """``R = [s]B`` is a prime-order point, so the ``R`` rule is not it either.

        Only the rule on ``A`` can reject these. Pinning that keeps the three
        input rules separable when one of them is next changed.
        """
        blocked = {enc[:31] + bytes([enc[31] & 0x7F]) for _, enc in SMALL_ORDER_ENCODINGS}
        r_half = signature[:32]
        assert r_half[:31] + bytes([r_half[31] & 0x7F]) not in blocked


class TestPerKeyForgery:
    """One signature per canonically encoded small-order ``A``.

    Built by the ``j``-search described in the module docstring: no secret is
    involved, only ``n <= 8`` hash evaluations. These satisfy the group
    equation under their key, which is what makes them evidence.
    """

    @pytest.mark.parametrize("order,public_key,signature", PER_KEY_FORGERIES)
    def test_forgery_is_rejected(self, order: int, public_key: bytes, signature: bytes) -> None:
        assert verify_both(signature, VECTOR_MSG, public_key) is False

    def test_all_eight_canonical_small_order_points_are_covered(self) -> None:
        """Every canonically encoded small-order point has a vector.

        Eight of the fourteen encodings are canonical; the other six are
        refused by INVARIANT-38 before the group equation is reached, so no
        such vector exists for them. If that ratio ever changes this assertion
        is where it surfaces.
        """
        canonical = {
            enc
            for _, enc in SMALL_ORDER_ENCODINGS
            if (int.from_bytes(enc, "little") & (2**255 - 1)) < P
            and not (enc[31] >> 7 and (int.from_bytes(enc, "little") & (2**255 - 1)) in (1, P - 1))
        }
        assert len(canonical) == 8
        assert {pk for _, pk, _ in PER_KEY_FORGERIES} == canonical


class TestSmallOrderR:
    """``R = identity`` with ``S = h*a mod L``, under a real public key.

    ``[S]B - R - [h]A`` is the identity exactly, so the group equation holds
    and INVARIANT-38's canonical-``R`` rule does not apply — this encoding *is*
    canonical, which is the difference from
    ``tests/c/test_ed25519_canonical_r.c``, whose vector uses the
    sign-bit-**set** spelling of the same point. Producing it needs the
    signer's own key, and that is the point: without this invariant a signer
    could mint a signature carrying no randomness at all and it would verify.

    No such vector exists for the other thirteen encodings: for a small-order
    ``T`` that is not the identity, ``[S]B = T + [h]A`` has no solution ``S``
    when ``A`` has prime order, because ``T`` is not in ``<B>``.
    """

    def test_identity_r_is_rejected(self) -> None:
        assert verify_both(R_IDENTITY_SIGNATURE, VECTOR_MSG, R_IDENTITY_PUBLIC_KEY) is False

    def test_the_public_key_is_a_real_one(self) -> None:
        """Not vacuous by way of the key: the same key verifies its own signature."""
        assert R_IDENTITY_PUBLIC_KEY == GENUINE_PUBLIC_KEY
        assert verify_both(GENUINE_SIGNATURE, VECTOR_MSG, GENUINE_PUBLIC_KEY) is True

    def test_the_r_half_is_the_canonical_identity_encoding(self) -> None:
        """Sign bit clear, so INVARIANT-38 is not what rejects it."""
        assert R_IDENTITY_SIGNATURE[:32] == IDENTITY
        assert R_IDENTITY_SIGNATURE[31] >> 7 == 0


class TestSmokeCoverage:
    """Rejected before the fix and after it — named so nobody counts it.

    Measured: 0 of 14 accepted both ways, because a signature made under a
    different key fails the group equation on its own. Kept for end-to-end
    coverage of all fourteen encodings and because a future refactor could
    make them discriminating.
    """

    @pytest.mark.parametrize("label,encoding", SMALL_ORDER_ENCODINGS)
    def test_smoke_small_order_public_key(self, label: str, encoding: bytes) -> None:
        assert verify_both(GENUINE_SIGNATURE, VECTOR_MSG, encoding) is False

    @pytest.mark.parametrize("label,encoding", SMALL_ORDER_ENCODINGS)
    def test_smoke_small_order_r_half(self, label: str, encoding: bytes) -> None:
        signature = encoding + GENUINE_SIGNATURE[32:]
        assert verify_both(signature, VECTOR_MSG, GENUINE_PUBLIC_KEY) is False


class TestTheFourteenEncodings:
    """The table itself: seven ``y`` values under both sign bits, and nothing else."""

    def test_there_are_exactly_fourteen(self) -> None:
        assert len(SMALL_ORDER_ENCODINGS) == 14
        assert len({enc for _, enc in SMALL_ORDER_ENCODINGS}) == 14

    def test_they_are_seven_y_values_under_both_sign_bits(self) -> None:
        ys = {int.from_bytes(enc, "little") & (2**255 - 1) for _, enc in SMALL_ORDER_ENCODINGS}
        y8a = 0x05FC536D880238B13933C6D305ACDFD5F098EFF289F4C345B027B2C28F95E826
        y8b = 0x7A03AC9277FDC74EC6CC392CFA53202A0F67100D760B3CBA4FD84D3D706A17C7
        assert ys == {0, 1, y8a, y8b, P - 1, P, P + 1}

    def test_only_p_and_p_plus_one_come_from_the_non_canonical_band(self) -> None:
        """``[p, 2^255)`` holds nineteen values; exactly two reduce into the set.

        This is what makes the fourteen complete rather than a sample. The
        sweep is cheap enough to run rather than cite.
        """
        y8a = 0x05FC536D880238B13933C6D305ACDFD5F098EFF289F4C345B027B2C28F95E826
        y8b = 0x7A03AC9277FDC74EC6CC392CFA53202A0F67100D760B3CBA4FD84D3D706A17C7
        small = {0, 1, y8a, y8b, P - 1}
        assert {y for y in range(P, 2**255) if y % P in small} == {P, P + 1}


class TestPositiveControl:
    """What must still be accepted. Without this the module passes on a verifier
    that returns ``False`` unconditionally."""

    def test_the_reference_generated_signature_verifies(self) -> None:
        assert verify_both(GENUINE_SIGNATURE, VECTOR_MSG, GENUINE_PUBLIC_KEY) is True

    @pytest.mark.parametrize("message,signature,public_key", RFC8032_VECTORS)
    def test_rfc8032_section_7_1(self, message: bytes, signature: bytes, public_key: bytes) -> None:
        assert verify_both(signature, message, public_key) is True

    def test_freshly_generated_signatures_verify(self) -> None:
        """Fixed vectors cannot show that the sign path is unaffected; this can."""
        for _ in range(8):
            public_key, secret_key = native_ed25519_keypair()
            signature = native_ed25519_sign(VECTOR_MSG, secret_key)
            assert verify_both(signature, VECTOR_MSG, public_key) is True
            assert public_key not in {enc for _, enc in SMALL_ORDER_ENCODINGS}


class TestMixedBatch:
    """Batch cannot be answering "reject everything"."""

    def test_one_genuine_entry_survives_the_company_it_keeps(self) -> None:
        entries = [(VECTOR_MSG, GENUINE_SIGNATURE, GENUINE_PUBLIC_KEY)]
        entries += [(VECTOR_MSG, sig, IDENTITY) for _, sig in UNIVERSAL_FORGERIES]
        entries += [(VECTOR_MSG, sig, pk) for _, pk, sig in PER_KEY_FORGERIES]
        entries.append((VECTOR_MSG, R_IDENTITY_SIGNATURE, R_IDENTITY_PUBLIC_KEY))

        results = native_ed25519_batch_verify(entries)
        assert results[0] is True
        assert results[1:] == [False] * (len(entries) - 1)

    def test_batch_matches_single_entry_for_entry(self) -> None:
        """The inheritance claim, stated over the whole corpus at once."""
        entries = [(VECTOR_MSG, GENUINE_SIGNATURE, GENUINE_PUBLIC_KEY)]
        entries += [
            (msg, sig, IDENTITY) for _, sig in UNIVERSAL_FORGERIES for msg in UNIVERSAL_MSGS
        ]
        entries += [(VECTOR_MSG, sig, pk) for _, pk, sig in PER_KEY_FORGERIES]
        entries += [(VECTOR_MSG, GENUINE_SIGNATURE, enc) for _, enc in SMALL_ORDER_ENCODINGS]
        entries += [
            (VECTOR_MSG, enc + GENUINE_SIGNATURE[32:], GENUINE_PUBLIC_KEY)
            for _, enc in SMALL_ORDER_ENCODINGS
        ]
        entries += [(msg, sig, pk) for msg, sig, pk in RFC8032_VECTORS]

        batched = native_ed25519_batch_verify(entries)
        singly = [native_ed25519_verify(sig, msg, pk) for msg, sig, pk in entries]
        assert batched == singly
