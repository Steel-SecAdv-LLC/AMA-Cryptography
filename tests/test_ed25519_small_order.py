"""Small-order Ed25519 public keys and R halves are rejected (INVARIANT-48).

``ama_ed25519_verify`` decides the **cofactorless** equation
``[S]B - R - [h]A = O`` — not the cofactored ``8([S]B - R - [h]A) = O`` that
ZIP-215 and libsodium's permissive mode decide — and until this invariant it
checked nothing about the *order* of ``A`` or ``R``. Set ``A`` to the identity
encoding and the ``[h]A`` term is the identity for every ``h``, so the equation
collapses to ``[S]B = R`` and the pair ``(R = [s]B, S = s)`` satisfies it for
**every message**. Measured against a pure-Python RFC 8032 reference at
``s in {1, 5, 12345}`` — all below ``L``, so the canonical-``S`` rule
(INVARIANT-26) does not block them — all three were ACCEPTED for all four
messages tried, through both the single and the batch entry point: 12 of 12
before the fix, 0 of 12 after. One 64-byte string, no secret, valid for
anything. It reached the package layer, where ``crypto_api`` embeds the public
key inside the package it verifies.

The finding is wider than the identity
--------------------------------------
The identity is the only key for which one signature works for every message,
but it is not the only forgeable one. For a small-order ``A`` of order ``n``,
``[h]A = [h mod n]A``, so an attacker holding no secret picks any ``S``, walks
``j`` over ``[0, n)``, sets ``R = [S]B - [j]A`` and keeps the first candidate
whose ``h = H(R || A || M)`` satisfies ``h == j (mod n)``. One in ``n``
candidates lands and ``n <= 8``. Constructed for all **eight** canonically
encoded small-order points: 8 of 8 accepted before the fix, 0 of 8 after.
Those eight are the load-bearing vectors here.

Why the obvious test would prove nothing
----------------------------------------
``tests/test_ed25519_canonical_y.py`` records what went wrong the last two
times this invariant family was tested, and the lesson applies verbatim: **a
rejection is only evidence when something that differs from it in exactly one
respect is accepted.** Putting a *genuine* signature to a small-order public
key and asserting ``False`` is vacuous — verify also returns ``False`` for the
wrong-key reason. Measured on this tree: 0 of 14 accepted both before and
after the fix. Those assertions live in :class:`TestSmokeCoverage` and are
named as smoke, not counted as coverage.

Every vector that *is* coverage satisfies the group equation under its
small-order input, so only the INVARIANT-48 predicate can reject it. The
library cannot produce such a signature — its signer has no way to emit one —
so they are fixed data, generated by a pure-Python RFC 8032 reference whose
own correctness is pinned by the §7.1 vectors in :class:`TestPositiveControl`.

Six encodings have no forgery vector
------------------------------------
Six of the fourteen never reach the group equation even without this fix:
``y = p`` and ``y = p+1`` under either sign fail INVARIANT-38's ``y < p`` rule,
and ``y = 1`` or ``y = p-1`` with the x-sign bit **set** fail its ``x = 0``
sign rule. A discriminating vector cannot be built for them because the
decoder refuses the encoding. ``tests/c/test_ed25519_small_order.c`` pins those
six directly against ``ama_ed25519_point_is_small_order()``, which this module
cannot reach — the predicate is a ``static inline`` in a private header with no
C-ABI symbol, so the Python side asserts behaviour and the C side asserts the
predicate.

Batch
-----
``ama_ed25519_batch_verify`` is an unconditional per-entry loop over
``ama_ed25519_verify``, so it inherits the rule by construction rather than by
a second copy of it. That is asserted rather than assumed: every vector below
is put to both entry points and the two verdicts compared.
"""

