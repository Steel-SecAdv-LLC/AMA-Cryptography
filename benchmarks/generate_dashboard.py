"""
Performance dashboard generator (self-contained HTML).

Reads the two measurement artefacts the repo already produces —
`benchmark_runner.py --output` (the regression-gated Python-path suite) and
`build/bin/benchmark_c_raw` (raw C latency/throughput) — plus
`benchmarks/baseline.json`, and renders a single static HTML page.

Why this exists
---------------
The previous dashboard (`assets/performance_dashboard.png`, generated by
`tools/generate_dashboards.py`) was a rasterised matplotlib grid. It had gone
stale in ways a PNG cannot signal: it was titled **v2.1.5** against a 3.4.0
library, its axis and value labels overlapped, its ASCII summary panel repeated
its own title forty times, one grid cell was empty, and it encoded a four-part
time breakdown as a pie chart. None of that is visible to a regression gate,
because a PNG carries no assertions.

Design rules this generator follows (see the project's data-viz guidance):

* **Form follows the data's job.** Throughput spans 710 -> 1.7M ops/s, so it is
  a horizontal bar on a log axis, not a pie and not a dual-axis chart. The
  optimisation story is a paired before/after bar. Headline facts are stat
  tiles, because a single number is not a chart.
* **Colour is assigned by role, in fixed slot order, never cycled** — one hue
  per primitive family, validated for CVD separation in both light and dark
  mode before use (worst adjacent dE 9.1 light / 8.4 dark against a >=8 target).
* **No colour-alone encoding.** Every bar carries a direct value label and every
  chart has a table view, which is also the relief required for the three
  light-mode hues that sit below 3:1 contrast.
* **Dark mode is selected, not flipped** — its own validated steps from the same
  ramps, under both the OS media query and the explicit theme toggle.
* **It regenerates.** The numbers come from the JSON artefacts, so the page
  cannot silently drift from the measurements the way a committed PNG did.

Usage
-----
    python benchmarks/benchmark_runner.py --output /tmp/bench.json
    ./build/bin/benchmark_c_raw > /tmp/rawc.txt
    python benchmarks/generate_dashboard.py \\
        --bench /tmp/bench.json --raw-c /tmp/rawc.txt \\
        --out benchmarks/dashboard.html
"""

